STRUCK = re.compile(r"^\d{1,3}(?:-bis)?(?:[（(][^）)]*[）)])?[.、]\s*[⭐🔴⚖️✅\s]*~~")


def strip_paren(title):
    """去掉标题里第一个括注及其后内容,取稳定的标题本体。"""
    for ch in ("(", "("):
        i = title.find(ch)
        if i > 0:
            title = title[:i]
    return title.strip()


def clean_title(text):
    """条目标题:剥掉星标/删除线/加粗记号,保留原文用字(⛔ 连删除线内的原文一起吃掉——
    划线=已销号的案底,标题本体正在里面)。"""
    text = text.strip()
    text = re.sub(r"^[⭐🔴⚖️✅~*\s]+", "", text)
    text = text.replace("~~", "").replace("**", "")
    return text.strip()


