def anchored(line, anchor):
    """锚匹配:行首(容行首空白)是锚 ⇒ 命中。⛔ 行内包含,见 AUTO_ANCHOR 注释。"""
    return line.lstrip().startswith(anchor)

# 条目行:行首编号 + 可选 `-bis` + 可选括注 + `.` + 空白。
